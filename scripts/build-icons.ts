/**
 * Generates the icon glyphs from the curated set (`src/ui/icons/curated.ts`, D-179).
 *
 *   pnpm icons         write src/ui/icons/glyphs/<name>.ts (one module per icon) and src/ui/icons/registry.ts
 *   pnpm icons:check   fail if either committed file is stale or was hand-edited
 *
 * Each icon becomes its own module with one plain-data export (`IconRefresh = { name, node }`) that
 * `<Icon icon={…}>` draws. One module per icon because the bundler chunks by module: a shared
 * multi-icon module would ship every icon any client component uses on every page that uses one.
 * Data, not components: a glyph can be passed from a server component to a client one as a prop. The shapes come from `lucide-react` (ISC), a dev dependency used only here.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { CURATED_ICONS } from "../src/ui/icons/curated";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GLYPHS_DIR = join(ROOT, "src/ui/icons/glyphs");
const REGISTRY = join(ROOT, "src/ui/icons/registry.ts");
const require = createRequire(join(ROOT, "package.json"));
const LUCIDE_ICONS = join(dirname(require.resolve("lucide-react/package.json")), "dist/esm/icons");

type Node = [tag: string, attrs: Record<string, string | number>][];

/** `chevron-down` → `IconChevronDown`. */
export const exportName = (name: string) =>
  `Icon${name
    .split("-")
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("")}`;

/** Lucide keeps renamed icons as `export { default } from './new-name.mjs'`; follow those to the data. */
async function lucideNode(file: string): Promise<Node> {
  const path = join(LUCIDE_ICONS, `${file}.mjs`);
  const alias = /export \{ default \} from '\.\/([\w-]+)\.mjs'/.exec(readFileSync(path, "utf8"));
  if (alias) return lucideNode(alias[1]!);
  const loaded = (await import(pathToFileURL(path).href)) as { __iconData?: { node: Node } };
  if (!loaded.__iconData) throw new Error(`lucide-react/${file} has no __iconData`);
  // Lucide's React keys are not needed: <Icon> keys the children by position.
  return loaded.__iconData.node.map(([tag, { key: _key, ...attrs }]) => [tag, attrs]);
}

const HEADER = `// Generated by scripts/build-icons.ts from src/ui/icons/curated.ts — do not edit; run \`pnpm icons\`.`;

/** Every generated file, path → content (unformatted). */
async function render(): Promise<Map<string, string>> {
  const names = Object.keys(CURATED_ICONS) as (keyof typeof CURATED_ICONS)[];
  const entries = await Promise.all(names.map(async (name) => ({ name, node: await lucideNode(CURATED_ICONS[name]) })));
  const files = new Map<string, string>();
  for (const { name, node } of entries) {
    files.set(
      join(GLYPHS_DIR, `${name}.ts`),
      [
        HEADER,
        "// Shape: lucide-react (ISC). One module per icon so a page only ships the glyphs it renders (D-179).",
        "",
        'import type { IconGlyph } from "../glyph";',
        "",
        `export const ${exportName(name)}: IconGlyph<${JSON.stringify(name)}> = { name: ${JSON.stringify(name)}, node: ${JSON.stringify(node)} };`,
        "",
      ].join("\n"),
    );
  }
  files.set(
    REGISTRY,
    [
      HEADER,
      "//",
      "// Every glyph by name — for Storybook and tests only. App code imports single glyphs from",
      "// `@/ui/icons/glyphs/<name>`; ESLint refuses this module elsewhere because it would ship the whole set (D-179).",
      "",
      'import type { CURATED_ICONS } from "./curated";',
      'import type { IconGlyph } from "./glyph";',
      ...entries.map(({ name }) => `import { ${exportName(name)} } from "./glyphs/${name}";`),
      "",
      "export type IconName = keyof typeof CURATED_ICONS;",
      "",
      "export const ICONS: { readonly [N in IconName]: IconGlyph<N> } = {",
      ...names.map((name) => `  ${JSON.stringify(name)}: ${exportName(name)},`),
      "};",
      "",
      "export const ICON_NAMES = Object.keys(ICONS) as IconName[];",
      "",
    ].join("\n"),
  );
  return files;
}

async function main(): Promise<void> {
  const files = await render();
  const check = process.argv.includes("--check");
  // Prettier formats the committed files; compare and write through it so `format:check` agrees.
  const prettier = await import("prettier");
  const options = (await prettier.resolveConfig(REGISTRY)) ?? {};
  const relative = (path: string) => path.replace(`${ROOT}/`, "");
  let stale = false;
  mkdirSync(GLYPHS_DIR, { recursive: true });
  for (const [path, source] of files) {
    const content = await prettier.format(source, { ...options, filepath: path });
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === content) continue;
    if (check) {
      console.error(`${relative(path)} is stale — run \`pnpm icons\`.`);
      stale = true;
    } else {
      writeFileSync(path, content);
      console.info(`wrote ${relative(path)}`);
    }
  }
  // A glyph whose key left the curated set is removed (and is stale under --check).
  for (const file of readdirSync(GLYPHS_DIR)) {
    const path = join(GLYPHS_DIR, file);
    if (files.has(path)) continue;
    if (check) {
      console.error(`${relative(path)} is not in the curated set — run \`pnpm icons\`.`);
      stale = true;
    } else {
      rmSync(path);
      console.info(`removed ${relative(path)}`);
    }
  }
  if (stale) process.exit(1);
}

void main();
